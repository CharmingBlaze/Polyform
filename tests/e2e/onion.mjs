// E2E: onion skin — past (red) / future (green) wireframe ghosts around the playhead.
import { chromium } from 'playwright-core'
const url = process.argv[2] || 'http://127.0.0.1:5173/'
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []; p.on('pageerror', e => errs.push(e.message))
await p.goto(url); await p.waitForFunction(() => window.__polyform && window.__polyformScene); await p.waitForTimeout(400)
const results = []
const check = (name, ok, info = '') => results.push([name, !!ok, info])
const S = (fn, arg) => p.evaluate(fn, arg)
const frame = () => p.waitForTimeout(120)

await S(() => window.__polyform.getState().openSample('character'))
await p.click('[data-testid="ws-animate"]'); await frame()
await S(() => window.__polyform.getState().set({ frame: 6, maximized: 1, onion: false, onionSteps: 2 }))
await frame()
const ghosts = () => S(() => window.__polyformScene.onionObjs.filter(o => o.visible).length)
check('onion off: no ghosts', (await ghosts()) === 0)
await p.click('[data-testid="onion"]'); await frame()
check('onion on: past + future ghosts at steps=2', (await ghosts()) === 4, String(await ghosts()))
const cols = await S(() => window.__polyformScene.onionObjs.filter(o => o.visible).map(o => '#' + (o.material.color.getHexString())))
check('past ghosts are red, future are green', cols.filter(c => c === '#ff6b6b').length === 2 && cols.filter(c => c === '#5fd38d').length === 2, JSON.stringify(cols))
await p.locator('[data-testid="onion-steps"]').fill('1'); await frame()
check('steps=1: one past + one future', (await ghosts()) === 2)
await S(() => window.__polyform.getState().set({ frame: 0 })); await frame()
check('at frame 0 only future ghosts show', (await ghosts()) === 1)
await S(() => window.__polyform.getState().set({ frame: 6, onionSteps: 3 })); await frame()
check('steps=3: six ghosts', (await ghosts()) === 6)
await p.screenshot({ path: '/workspace/shot-onion.png' })
await p.click('[data-testid="onion"]'); await frame()
check('toggle off clears the ghosts', (await ghosts()) === 0)
await b.close()
for (const [n, ok, info] of results) console.log(ok ? 'PASS' : 'FAIL', n, ok ? '' : info)
console.log('pageErrors', JSON.stringify(errs))
process.exit(results.every(r => r[1]) && !errs.length ? 0 : 1)
