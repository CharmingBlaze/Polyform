// Object | Vertex | Edge | Face switch in the header (keys 1–4, Tab), Object mode picking / transforms / duplicate /
// delete / Outliner sync, no hint bar, and the side panels' collapse controls (buttons, Ctrl+[ / Ctrl+] / Ctrl+\,
// View menu, double-click, per-workspace state, quick slide honouring prefers-reduced-motion).
import { chromium } from 'playwright-core'
const url = process.argv[2] || 'http://127.0.0.1:5173/'
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1280, height: 720 } })
const errs = []
p.on('pageerror', e => errs.push(e.message))
const results = []
const check = (name, ok, info = '') => { results.push([name, !!ok]); console.log(`${ok ? 'ok ' : 'FAIL'} ${name}${ok ? '' : ' ' + info}`) }
const S = (fn, arg) => p.evaluate(fn, arg)
const frame = (ms = 120) => p.waitForTimeout(ms)
const slide = async () => { await p.waitForTimeout(40); await p.waitForFunction(() => !document.querySelector('.main.anim')); await p.waitForTimeout(40) }
await p.goto(url); await p.waitForFunction(() => window.__polyform && window.__polyformScene && window.__polyformViews)
await S(() => localStorage.clear()); await p.reload(); await p.waitForFunction(() => window.__polyform && window.__polyformScene && window.__polyformViews); await frame(300)
const st = () => S(() => { const s = window.__polyform.getState(); return { mode: s.selectMode, subs: s.subModes, faces: [...s.selFaces].sort((a, b) => a - b), groups: s.model.groups.length } })

// ---- the switch ----
check('header has Object | Vertex | Edge | Face with icons and labels', (await p.locator('.header [data-testid="mode-switch"] button').allTextContents()).join('|') === 'Object|Vertex|Edge|Face' && (await p.locator('.header [data-testid="mode-switch"] svg').count()) === 4)
check('the status bar no longer has its own mode row; no hint bar', (await p.locator('.status [data-testid="mode-switch"]').count()) === 0 && (await p.locator('[data-testid="hint-bar"]').count()) === 0)
check('Model has no Joints button', (await p.locator('[data-testid="mode-joint"]').count()) === 0)
await p.mouse.move(640, 360)
const keyMode = async k => { await p.keyboard.press(k); await frame(60); return (await st()).mode }
check('keys: 1 Object, 2 Vertex, 3 Edge, 4 Face', [await keyMode('1'), await keyMode('2'), await keyMode('3'), await keyMode('4')].join() === 'object,vertex,edge,face')
check('Tab: Object, Tab again: back to the last edit mode (Face)', (await keyMode('Tab')) === 'object' && (await keyMode('Tab')) === 'face')
await p.keyboard.press('3'); await frame(60)
check('the switch shows the mode (aria-checked)', (await p.getAttribute('[data-testid="mode-edge"]', 'aria-checked')) === 'true' && (await p.getAttribute('[data-testid="mode-face"]', 'aria-checked')) === 'false')
await p.click('[data-testid="mode-face"]', { modifiers: ['Shift'] }); await frame(60)
check('Shift+click on a mode combines (Edge + Face)', JSON.stringify((await st()).subs.sort()) === '["edge","face"]')
await p.click('[data-testid="ws-rig"]'); await frame()
check('Rig shows a Joints mode (5)', await p.isVisible('[data-testid="mode-joint"]') && (await keyMode('5')) === 'joint')
await p.click('[data-testid="ws-model"]'); await frame()

// ---- Object mode on two boxes ----
await S(() => {
  const s = window.__polyform.getState(), m = s.model
  m.verts = []; m.vbone = []; m.faces = []; m.groups = []; s.loadModel(m)
  window.__polyform.getState().runOp('add.box', { w: 1, h: 1, d: 1, x: -1.2, y: 0, z: 0 })
  window.__polyform.getState().runOp('add.box', { w: 1, h: 1, d: 1, x: 1.2, y: 0, z: 0 })
  const t = window.__polyform.getState(); t.set({ maximized: 1, tool: 'select' }); t.setSelectMode('object'); t.selectNone()
})
await frame(300)
const centre = g => S(g => { const c = window.__polyformViews[1], m = window.__polyform.getState().model, V = c.camera.position.constructor, r = c.el.getBoundingClientRect(); const vs = [...new Set(m.faces.filter(f => f.g === g).flatMap(f => f.v))]; const q = new V(...[0, 1, 2].map(k => vs.reduce((a, v) => a + m.verts[v][k], 0) / vs.length)).project(c.camera); return { x: r.left + (q.x * .5 + .5) * c.w, y: r.top + (-q.y * .5 + .5) * c.h } }, g)
const A = await centre(0), B = await centre(1)
const facesOf = g => S(g => window.__polyform.getState().model.faces.map((f, i) => (f.g === g ? i : -1)).filter(i => i >= 0), g)
const fA = await facesOf(0), fB = await facesOf(1)
await p.mouse.click(A.x, A.y); await frame()
check('Object mode: a click picks the whole object', JSON.stringify((await st()).faces) === JSON.stringify(fA), JSON.stringify(await st()))
check('…outlined: its 12 edges drawn in the selection colour', (await S(() => window.__polyformScene.selEdgeGeo.attributes.position.count)) === 24, String(await S(() => window.__polyformScene.selEdgeGeo.attributes.position.count)))
check('…and the Outliner row lights up', ((await p.getAttribute('[data-testid="ol-obj-0"]', 'class')) || '').includes('on'))
const shiftClick = async q => { await p.keyboard.down('Shift'); await p.mouse.click(q.x, q.y); await p.keyboard.up('Shift'); await frame() }
await shiftClick(B)
check('Shift+click adds the second object', (await st()).faces.length === 12)
await shiftClick(A)
check('Shift+click on a selected object removes it', JSON.stringify((await st()).faces) === JSON.stringify(fB))
await S(() => window.__polyform.getState().selectNone()); await frame()
await p.keyboard.down('Control'); await p.mouse.move(Math.min(A.x, B.x) - 80, A.y - 80); await p.mouse.down(); await p.mouse.move(Math.max(A.x, B.x) + 80, B.y + 80, { steps: 6 }); await p.mouse.up(); await p.keyboard.up('Control'); await frame()
check('Ctrl+drag box selects both objects', (await st()).faces.length === 12, JSON.stringify(await st()))
// G moves the object's transform, not its points
await p.mouse.click(B.x, B.y); await frame()
const v0 = await S(() => JSON.stringify(window.__polyform.getState().model.verts))
await p.mouse.move(B.x, B.y); await p.keyboard.press('g'); await p.mouse.move(B.x + 60, B.y, { steps: 5 }); await p.mouse.click(B.x + 60, B.y); await frame()
const xf = await S(() => window.__polyform.getState().model.groups.map(g => g.xf.pos))
check('G in Object mode moves the object around its origin (transform changes, points do not)', xf[1][0] > 0.05 && xf[0][0] === 0 && v0 === await S(() => JSON.stringify(window.__polyform.getState().model.verts)), JSON.stringify(xf))
await p.keyboard.press('Shift+d'); await frame()
let s1 = await st()
check('Shift+D duplicates the object as a new object (selected)', s1.groups === 3 && s1.faces.length === 6 && await S(() => { const s = window.__polyform.getState(); return [...s.selFaces].every(f => s.model.faces[f].g === 2) && s.model.groups[2].xf.pos[0] === s.model.groups[1].xf.pos[0] }))
await p.keyboard.press('Delete'); await frame()
s1 = await st()
check('Delete removes the selected object', s1.groups === 2 && (await S(() => window.__polyform.getState().model.faces.length)) === 12)
await p.click('[data-testid="ol-obj-0"]'); await frame()
check('Outliner click selects that object in Object mode', (await st()).mode === 'object' && JSON.stringify((await st()).faces) === JSON.stringify(fA))
await S(() => window.__polyform.getState().set({ maximized: null })); await frame(200)
await p.screenshot({ path: '/workspace/shot-objectmode.png' })

// ---- side panels ----
const sides = () => S(() => { const m = document.querySelector('.main'); return { l: m.dataset.left, r: m.dataset.right, rail: Math.round(document.querySelector('.rail').getBoundingClientRect().width), right: Math.round(document.querySelector('.right-col').getBoundingClientRect().width) } })
let sd = await sides()
check('1280: both panels open, default widths (rail 144, side column 256: wide enough for every tab)', sd.l === 'open' && sd.r === 'open' && sd.rail === 144 && sd.right === 256, JSON.stringify(sd))
check('the tool-panel chevron and the side rail are visible without hovering', +(await p.locator('[data-testid="rail-collapse"]').evaluate(e => getComputedStyle(e).opacity)) > 0.4 && await p.locator('[data-testid="side-rail"]').isVisible())
await p.mouse.move(640, 360)
await p.keyboard.press('Control+BracketLeft'); await slide()
sd = await sides(); check('Ctrl+[ collapses the tool panel to icons', sd.l === 'icons' && sd.rail <= 48, JSON.stringify(sd))
await p.keyboard.press('Control+BracketRight'); await slide()
sd = await sides(); check('Ctrl+] collapses the side panel to icons', sd.r === 'icons' && sd.right <= 48, JSON.stringify(sd))
await p.keyboard.press('Control+Backslash'); await slide()
sd = await sides(); check('Ctrl+\\ (focus) with both hidden brings both back', sd.l === 'open' && sd.r === 'open', JSON.stringify(sd))
await p.keyboard.press('Control+Backslash'); await slide()
sd = await sides(); check('Ctrl+\\ again hides both (full-viewport focus)', sd.l === 'icons' && sd.r === 'icons', JSON.stringify(sd))
await p.click('[data-testid="mb-view"]'); await frame(80)
const chk = id => p.getAttribute(`[data-testid="mi-view-${id}"]`, 'aria-checked')
check('View menu: Tool Panel / Side Panel unchecked, Focus checked', (await chk('toolPanel')) === 'false' && (await chk('sidePanel')) === 'false' && (await chk('focus')) === 'true')
await p.click('[data-testid="mi-view-toolPanel"]'); await slide()
sd = await sides(); check('View → Tool Panel shows it again', sd.l === 'open' && sd.r === 'icons')
await p.click('[data-testid="side-scene"]'); await slide()
sd = await sides(); check('an icon on the strip expands the panel at that tab', sd.r === 'open' && (await S(() => window.__polyform.getState().sideTab)) === 'scene')
await p.locator('[data-testid="side-handle"]').dblclick(); await slide()
check('double-clicking the splitter collapses', (await sides()).r === 'icons')
await p.click('[data-testid="side-rail"] .rail-btn.on'); await slide()
await p.click('[data-testid="side-rail"] .rail-btn.on'); await slide()
check('clicking the active rail icon collapses the side panel', (await sides()).r === 'icons')
await p.click('[data-testid="ws-paint"]'); await slide()
check('per workspace: Paint keeps its own (open) side panel', (await sides()).r === 'open')
await p.click('[data-testid="ws-model"]'); await slide()
check('…and Model remembers its collapsed one', (await sides()).r === 'icons')
await p.reload(); await p.waitForFunction(() => window.__polyform && window.__polyformScene); await frame(300)
await p.locator('[data-testid="dialog-restore"]').click({ timeout: 4000 }).catch(() => {}) // rolling backup: answer the restore prompt
check('…after a reload too', (await sides()).r === 'icons' && (await S(() => JSON.parse(localStorage.getItem('polyform.ui.v1')).panels.model.right)) === true)
const tr = () => S(() => getComputedStyle(document.querySelector('.main')).transitionDuration)
await p.click('[data-testid="side-rail"] .rail-btn.on'); const dur = await tr(); await slide()
